// Generates THIRD_PARTY_NOTICES.md from the packages actually bundled into dist/extension.js
// (read from dist/metafile.json written by esbuild.mjs). Run after a production build.
import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';

const metafile = JSON.parse(readFileSync('dist/metafile.json', 'utf8'));
const packages = new Map();

for (const input of Object.keys(metafile.inputs)) {
  const parts = input.split('/');
  const index = parts.lastIndexOf('node_modules');
  if (index === -1) {
    continue;
  }
  const nameParts = parts[index + 1]?.startsWith('@') ? parts.slice(index + 1, index + 3) : parts.slice(index + 1, index + 2);
  const dir = realpathSync(path.resolve(...parts.slice(0, index + 1 + nameParts.length)));
  if (!packages.has(dir)) {
    packages.set(dir, JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')));
  }
}

const sections = [...packages.entries()]
  .sort(([, a], [, b]) => a.name.localeCompare(b.name))
  .map(([dir, pkg]) => {
    const licenseFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\..*)?$/i.test(f));
    const noticeFile = readdirSync(dir).find((f) => /^notice(\..*)?$/i.test(f));
    const text = licenseFile ? readFileSync(path.join(dir, licenseFile), 'utf8').trim() : `License: ${pkg.license ?? 'UNKNOWN'} (no license file shipped)`;
    const notice = noticeFile && existsSync(path.join(dir, noticeFile)) ? `\n\nNOTICE:\n\n${readFileSync(path.join(dir, noticeFile), 'utf8').trim()}` : '';
    return `## ${pkg.name}@${pkg.version} — ${pkg.license ?? 'UNKNOWN'}\n\n${pkg.homepage ?? pkg.repository?.url ?? ''}\n\n\`\`\`text\n${text}${notice}\n\`\`\``;
  });

writeFileSync(
  'THIRD_PARTY_NOTICES.md',
  `# Third-party notices\n\nProbato PR bundles the following open source packages into \`dist/extension.js\`. Generated by \`scripts/third-party-notices.mjs\` from the build metafile.\n\n${sections.join('\n\n')}\n`,
);
console.log(`THIRD_PARTY_NOTICES.md: ${packages.size} bundled package(s): ${[...packages.values()].map((p) => `${p.name}@${p.version} (${p.license})`).join(', ')}`);
